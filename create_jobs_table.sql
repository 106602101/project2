CREATE TABLE IF NOT EXISTS jobs (
    jobref CHAR(6) PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    summary VARCHAR(255) NOT NULL,
    salary_min DECIMAL(10,2) NOT NULL,
    salary_max DECIMAL(10,2) NOT NULL,
    employment_type VARCHAR(30) NOT NULL,
    location VARCHAR(100) NOT NULL,
    reports_to VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT chk_salary_range
        CHECK (salary_min <= salary_max)
);

CREATE TABLE IF NOT EXISTS job_responsibilities (
    responsibility_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    jobref CHAR(6) NOT NULL,
    responsibility_text VARCHAR(255) NOT NULL,
    display_order SMALLINT UNSIGNED NOT NULL DEFAULT 1,

    CONSTRAINT fk_responsibilities_job
        FOREIGN KEY (jobref)
        REFERENCES jobs(jobref)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS job_requirements (
    requirement_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    jobref CHAR(6) NOT NULL,
    requirement_type ENUM('essential', 'preferable') NOT NULL,
    requirement_text VARCHAR(255) NOT NULL,
    display_order SMALLINT UNSIGNED NOT NULL DEFAULT 1,

    CONSTRAINT fk_requirements_job
        FOREIGN KEY (jobref)
        REFERENCES jobs(jobref)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

